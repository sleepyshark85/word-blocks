/* ------------------------------------ §13.3a — the confirm screen, and when not */

test('S19 fires for a digraph, `gi` and `qu`, and `bò` skips it entirely', () => {
  // §13.3a: *"It appears **only** when the decomposition is not one letter per unit, i.e.
  // when a digraph or `gi` / `qu` is involved; `bò` skips it entirely."*
  assert.equal(analyse(vi, 'chó').needsConfirm, true, 'ch is two letters, one sound');
  assert.equal(analyse(vi, 'già').needsConfirm, true);
  assert.equal(analyse(vi, 'quả').needsConfirm, true);
  assert.equal(analyse(vi, 'bò').needsConfirm, false);
  // A two-letter RIME is not a reason to ask her: `mèo`'s boundary is where her own
  // spelling puts it, and asking about it would train her to dismiss the screen.
  assert.equal(analyse(vi, 'mèo').needsConfirm, false);
  assert.equal(analyse(vi, 'áo').needsConfirm, false);
  // English: any digraph.
  assert.equal(analyse(en, 'ship').needsConfirm, true);
  assert.equal(analyse(en, 'cat').needsConfirm, false);
});

test('the spans the confirm screen draws are the spans the board will draw', () => {
  for (const word of vi.words) {
    const choice = analyse(vi, word.text).choice;
    assert.deepEqual(
      spansOf(choice).map((s) => [s.start, s.end, s.kind]),
      word.spans.map((s) => [s.start, s.end, s.kind]),
      `${word.text}: the editor and the board disagree about the spans`,
    );
  }
  for (const word of en.words) {
    const choice = analyse(en, word.text).choice;
    assert.deepEqual(
      spansOf(choice).map((s) => [s.start, s.end, s.kind]),
      word.spans.map((s) => [s.start, s.end, s.kind]),
      `${word.text}: the editor and the board disagree about the spans`,
    );
  }
});

test('needsConfirm is exactly "some span covers more than one letter" in English', () => {
  for (const word of en.words) {
    const choice = analyse(en, word.text).choice;
    assert.equal(needsConfirm(choice), word.spans.some((s) => s.end - s.start > 1), word.text);
  }
});

