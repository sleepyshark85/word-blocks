test('K3/K4/K5 — all six toned forms are generated, stored, and the illegal ones are null', () => {
  const open = viRimeProposal('uông');
  assert.deepEqual(open.legalTones, ['ngang', 'huyen', 'sac', 'hoi', 'nga', 'nang']);
  assert.deepEqual(open.toned, {
    ngang: 'uông', huyen: 'uồng', sac: 'uống', hoi: 'uổng', nga: 'uỗng', nang: 'uộng',
  });
  // §5.2's checked-syllable rule, greyed on the screen and **null in the pack**.
  const stopped = viRimeProposal('oat');
  assert.deepEqual(stopped.legalTones, ['sac', 'nang']);
  assert.deepEqual(stopped.cells.filter((c) => c.legal).map((c) => c.tone), ['sac', 'nang']);
  for (const cell of stopped.cells) {
    if (!cell.legal) assert.equal(cell.form, null);
    else assert.equal(typeof cell.form, 'string');
  }
  // Every generated form is NFC, so it compares equal to what she types.
  for (const form of Object.values(open.toned)) assert.equal(form, form.normalize('NFC'));
});

test('K3 — the generator agrees with every rime already in the pack', () => {
  // The forms it will propose for a rime she adds are made the same way the 35 shipped
  // rimes were. If it disagrees with them it is wrong, and this is how we would know.
  for (const rime of vi.tiles.rime) {
    const proposed = viRimeProposal(rime.id);
    for (const tone of rime.legalTones) {
      assert.equal(proposed.toned[tone], rime.toned[tone],
        `rime ${rime.id} + ${tone}: proposed ${proposed.toned[tone]}, pack has ${rime.toned[tone]}`);
    }
  }
});

