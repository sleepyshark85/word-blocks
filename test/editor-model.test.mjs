/* ----------------------------------------------------- more than one reading */

test('`già` has two readings and the longest onset is offered first', () => {
  const looked = analyse(vi, 'già');
  // `gi`+`a` and `g`+`ia` are both real; they put the boundary in different places, which
  // is the whole reason `onsetLetterCount` is stored rather than derived.
  assert.ok(looked.parses.length >= 1);
  assert.equal(looked.choice.onset, 'gi', 'the standard analysis is the longest onset');
  if (looked.parses.length > 1) {
    const other = analyse(vi, 'già', 1).choice;
    assert.notEqual(other.onsetLetterCount, looked.choice.onsetLetterCount);
  }
  // An index out of range is clamped rather than throwing: it comes from a tap counter.
  assert.equal(analyse(vi, 'già', 99).choice.index, looked.parses.length - 1);
  assert.equal(analyse(vi, 'già', -4).choice.index, 0);
});

