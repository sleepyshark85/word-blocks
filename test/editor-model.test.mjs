/* -------------------------------------------- L7 — deleting a word moves nothing */

test('L7 — deleting her last word behind a letter does not move a single character', () => {
  // **This is the criterion that exists *because* of the editor.** `ui.md` §8.1 draws
  // every character of `inventoryOrder` whether or not a word uses it, and L7 is what
  // stops the board from reshuffling when the word list shrinks. The slot the child has
  // learned is a pure function of `inventoryOrder` and the device, and nothing else —
  // not the word list, not the session, not a random source (E12, B7).
  const inputs = readPackInputs(packDir('vi-seed'));
  const before = createGame(vi, { pages: [15, 14, 6] });

  // `k` has exactly one word behind it in `vi-seed` (`kem`). Delete every word that uses
  // it — which is the strongest form of the case, because the letter then leads nowhere.
  const victim = 'k';
  const doomed = vi.words.filter((w) => w.letters.includes(victim)).map((w) => w.id);
  assert.ok(doomed.length > 0, `no word uses "${victim}"; pick another letter`);

  const after = createGame(
    resolvePack({
      language: 'vi',
      manifest: inputs.manifest,
      words: inputs.words.filter((w) => !doomed.includes(w.id)),
      hasMedia: inputs.hasMedia,
    }),
    { pages: [15, 14, 6] },
  );

  // 1. The alphabet is unchanged, in order.
  assert.deepEqual(after.pack.inventoryOrder, before.pack.inventoryOrder);
  // 2. **Every character is in the same cell on the same page.** Byte for byte.
  const slots = (game) => game.inventory.symbols.map((s) => `${s.id}@${s.page}:${s.slot}`);
  assert.deepEqual(slots(after), slots(before));
  assert.equal(after.pageCount, before.pageCount);
  // 3. The letter is still on the board, and it is now permanently flat.
  const cell = after.inventory.symbols.find((s) => s.id === victim);
  assert.ok(cell, `"${victim}" left the board when its last word was deleted`);
  assert.equal(tableView(after, createSession(after)).cells[cell.index].live, false);
  // 4. And it was live before, so the test is measuring something.
  assert.equal(tableView(before, createSession(before)).cells[cell.index].live, true);
});
