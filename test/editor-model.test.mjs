// **She types a word; the app derives the rest.** This is that, against the real packs.
//
// `content-pipeline.md` §3.7 and `ui.md` §13.7 E19 say `letters` and `onsetLetterCount`
// are written by the editor and never composed at runtime. The strongest available check
// on the thing that writes them is that it **reproduces every decomposition in both
// shipped packs from the spelling alone** — 47 Vietnamese words and 40 English ones,
// authored months earlier by a different tool from a different source. That is the first
// test below, and it is a fixture nobody can quietly weaken, because weakening it means
// changing the content.
//
// The rest is `ui.md` §13.3 / §13.3a: every screen his mother can land on, reached by
// asking the model what it says about the word that lands her there.

import test from 'node:test';
import assert from 'node:assert/strict';

import { viPack, enPack } from './helpers/load.mjs';
import {
  analyse, normaliseTyped, bareLetters, spansOf, needsConfirm, viRimeProposal,
  MAX_WORD_LETTERS, PROBLEMS,
} from '../src/editor/model.mjs';
import { buildWordRecord } from '../src/editor/wordFile.mjs';
import { buildList } from '../src/editor/list.mjs';
import { resolvePack, createGame, createSession, tableView } from '../src/engine/index.mjs';
import { readPackInputs, packDir } from './helpers/load.mjs';

const vi = viPack();
const en = enPack();

/* ------------------------------------------- the fixture nobody can weaken */

test('every vi-seed word is re-derived from its spelling alone, boundary included', () => {
  assert.equal(vi.words.length, 47, 'the fixture is the shipped pack; if it changed, re-read this');
  for (const word of vi.words) {
    const { choice, problem } = analyse(vi, word.text);
    assert.equal(problem, null, `${word.text}: ${problem && problem.code}`);
    const stored = word.syllables[0];
    assert.deepEqual(
      { onset: choice.onset, rime: choice.rime, tone: choice.tone },
      { onset: stored.onset, rime: stored.rime, tone: stored.tone },
      `${word.text} was read as a different syllable`,
    );
    assert.deepEqual(choice.letters, word.letters, `${word.text}: letters`);
    // **The boundary is the point.** `chó` is `c h | o`, and a first-vowel rule gets
    // `gi` and `qu` wrong, which is exactly why it is stored (C4f).
    assert.equal(choice.onsetLetterCount, word.onsetLetterCount, `${word.text}: boundary`);
  }
});

test('every en-seed word is re-derived, and `duck` is three sounds and four taps', () => {
  assert.equal(en.words.length, 40);
  for (const word of en.words) {
    const { choice, problem } = analyse(en, word.text);
    assert.equal(problem, null, `${word.text}: ${problem && problem.code}`);
    assert.deepEqual(choice.tiles, word.tiles, `${word.text}: sounds`);
    assert.deepEqual(choice.letters, word.letters, `${word.text}: taps`);
  }
  const duck = analyse(en, 'duck').choice;
  assert.deepEqual(duck.tiles, ['d', 'u', 'ck']);
  assert.deepEqual(duck.letters, ['d', 'u', 'c', 'k']);
  // Fewest tiles wins, and that is what puts `gg` together rather than apart.
  assert.deepEqual(analyse(en, 'egg').choice.tiles, ['e', 'gg']);
});

test('the derived record round-trips through the loader and becomes playable', () => {
  // The end-to-end claim: what the editor writes, the engine accepts. Anything less is a
  // decomposition that looks right on her screen and withholds the word on his.
  const inputs = readPackInputs(packDir('vi-seed'));
  const record = buildWordRecord(
    {
      id: 'wtest', text: 'mèo', images: [{ src: 'media/img/x.jpg' }],
      audio: { word: { src: 'media/aud/x.mp3' } }, draft: false,
      choice: analyse(vi, 'mèo').choice,
    },
    { language: 'vi' },
  );
  const resolved = resolvePack({
    language: 'vi',
    manifest: inputs.manifest,
    // `mèo` is already in the pack, so this word would clash on parts; drop the original.
    words: [...inputs.words.filter((w) => w.id !== 'meo'), record],
    hasMedia: (ref) => inputs.hasMedia(ref) || ref.startsWith('media/img/x') || ref.startsWith('media/aud/x'),
  });
  const built = resolved.wordById.wtest;
  assert.ok(built, `the editor's own record was withheld: ${JSON.stringify(
    resolved.catalogue.find((c) => c.id === 'wtest'),
  )}`);
  assert.deepEqual(built.letters, ['m', 'e', 'o']);
  assert.equal(built.onsetLetterCount, 1);
});

/* --------------------------------------------- normalisation at the boundary */

test('normalisation happens once, at the boundary, and NFD equals NFC', () => {
  // `CLAUDE.md`: *a word typed by the mother and a word generated by the pipeline must
  // compare equal.* A phone keyboard can hand back either form.
  // Written as an escape on purpose: an editor that normalises this file would
  // otherwise turn the test into a tautology without anything failing.
  const nfd = 'me\u0300o'; // m + e + COMBINING GRAVE + o
  assert.equal([...nfd].length, 4);
  assert.notEqual(nfd, 'mèo');
  assert.equal(normaliseTyped(nfd), 'mèo');
  assert.deepEqual(analyse(vi, nfd).choice.letters, ['m', 'e', 'o']);
  assert.equal(analyse(vi, nfd).choice.tone, 'huyen');
  // Trimmed, collapsed, folded — and D24 is untouched: nothing is ever upper-cased.
  assert.equal(normaliseTyped('  MÈO  '), 'mèo');
  assert.equal(normaliseTyped('Cat'), 'cat');
  assert.equal(normaliseTyped('máy   bay'), 'máy bay');
});

test('D20 — every letter the editor writes is lower case and one character', () => {
  for (const [pack, word] of [[vi, 'MÈO'], [en, 'DUCK']]) {
    const choice = analyse(pack, word).choice;
    for (const letter of choice.letters) {
      assert.equal(letter, letter.toLowerCase(), `${letter} is stored upper case`);
      assert.equal([...letter.normalize('NFC')].length, 1);
    }
  }
});

