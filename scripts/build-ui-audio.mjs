#!/usr/bin/env node
// Build the app's own (non-speech) sounds and the module that bundles them.
//
// `ui.md` §11.3 / §11.4 name the sounds that are not words. They are **bundled UI
// audio**, resident for the whole session, and they are not pack content: a pack can lose
// a photograph, but the announcement motif is the app's signature and must not be
// damageable — the same argument `content-pipeline.md` §5 makes for the fallback emoji.
//
// They are also synthesised rather than sourced, which closes a real risk: `docs/slices.md`
// defect 8 records that neither TTS engine grants redistribution rights inside a product.
// A sine and an exponential decay carry no such question.
//
//   node scripts/build-ui-audio.mjs
//
// Requires the `numpy` + `soundfile` venv in `tools/.venv` (see `docs/slices.md`).

import { execFileSync } from 'node:child_process';
import { readdirSync, writeFileSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'assets', 'audio');
const PY = path.join(ROOT, 'tools', '.venv', 'bin', 'python');

/** file name → the key `gameController` reads it under. */
const KEYS = {
  'motif-3.wav': 'motif3',
  'motif-4.wav': 'motif4',
  'seat.wav': 'seat',
  'knock.wav': 'knock',
  'unclick.wav': 'unclick',
  'page.wav': 'page',
  'shelf-bell.wav': 'shelfBell',
  'shelf-tip.wav': 'shelfTip',
};

if (!existsSync(PY)) {
  console.error(`tools/.venv is missing; see docs/slices.md for how to rebuild it`);
  process.exit(1);
}

execFileSync(PY, [path.join(ROOT, 'tools', 'gen-ui-audio.py'), OUT], { stdio: 'inherit' });

const present = new Set(readdirSync(OUT).filter((f) => f.endsWith('.wav')));
const missing = Object.keys(KEYS).filter((f) => !present.has(f));
if (missing.length > 0) {
  console.error(`the generator did not produce ${missing.join(', ')}`);
  process.exit(1);
}

const lines = Object.entries(KEYS)
  .map(([file, key]) => `  ${key}: require('./${file}'),`)
  .join('\n');

writeFileSync(path.join(OUT, 'index.js'), `// GENERATED by \`node scripts/build-ui-audio.mjs\`. Do not edit.
//
// The app's own sounds (\`ui.md\` §11.3, §11.4) — the announcement motif, the seat click,
// the disabled knock, the undo unclick, the page slide, the shelf bell and the
// shelf-tip phrase. Bundled in the binary, resident for the whole session, and shared by
// both language modes: \`acceptance-criteria.md\` R10 allows exactly these across the
// boundary, because they contain no speech in either language.
//
// The cheer is deliberately **not** here. It is one optional recording per pack, hers,
// and the app is complete without it (\`gameplay.md\` §5.2, \`ui.md\` §13.7 E14).

export const UI_AUDIO = {
${lines}
};
`);

console.log(`\nwrote ${path.relative(ROOT, path.join(OUT, 'index.js'))} with ${Object.keys(KEYS).length} sounds`);
