#!/usr/bin/env node
// Generate a pack's attribution notice from the pack itself.
//
//   node tools/pack-attributions.mjs packs/vi-seed            # writes ATTRIBUTION.md
//   node tools/pack-attributions.mjs packs/vi-seed --json     # the same data, for the app
//   node tools/pack-attributions.mjs packs/vi-seed --check    # exit 1 if it is out of date
//
// WHY GENERATED AND NOT MAINTAINED. `image-sourcing.md`: "an attributions screen,
// generated from the pack rather than maintained by hand". A hand-kept list is wrong the
// first time somebody adds a word on a phone, and being wrong here is a licence breach
// rather than a typo. So the obligation is discharged by walking the same `images[]`
// entries the game reads, and the *app* does exactly this at runtime for its credits
// screen. This file is the reference implementation and the CI check.
//
// The app must run the same walk over the LIVE pack, not ship this file's output —
// because the mother will add pictures after the build, and their licences must appear
// too. This output is for the repository and for review.

import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { readManifest, readWords, packPaths } from './lib/pack.mjs';
import { isOurs, licenceObligations, missingCredit } from './lib/licence.mjs';

const argv = process.argv.slice(2);
let packDir = null;
let asJson = false;
let check = false;
for (const a of argv) {
  if (a === '--json') asJson = true;
  else if (a === '--check') check = true;
  else if (a.startsWith('-')) { console.error(`unknown option ${a}`); process.exit(2); }
  else packDir = a;
}
if (!packDir) { console.error('usage: pack-attributions.mjs <pack-dir> [--json] [--check]'); process.exit(2); }

const read = readManifest(packDir);
if (!read) { console.error(`cannot read ${packDir}/pack.json`); process.exit(2); }
const manifest = read.manifest;

const entries = new Map(); // src -> record
const engines = new Map(); // engine label -> count
let ourImages = 0;

for (const { word } of readWords(packDir).ok) {
  for (const im of word.images ?? []) {
    if (!im?.src) continue;
    if (isOurs(im.source)) { ourImages += 1; continue; }
    if (!entries.has(im.src)) {
      entries.set(im.src, {
        src: im.src,
        title: im.title ?? path.basename(im.src),
        creator: im.creator ?? null,
        license: im.license ?? null,
        licenseUrl: im.licenseUrl ?? null,
        sourceUrl: im.sourceUrl ?? null,
        source: im.source ?? null,
        modified: im.modified ?? null,
        words: [],
      });
    }
    entries.get(im.src).words.push(word.text);
  }
  for (const a of Object.values(word.audio ?? {})) {
    if (a?.engine) engines.set(a.engine, (engines.get(a.engine) ?? 0) + 1);
  }
}
for (const group of Object.values(manifest.tiles ?? {})) {
  for (const t of group) {
    for (const a of Object.values(t.audio ?? {})) {
      if (a?.engine) engines.set(a.engine, (engines.get(a.engine) ?? 0) + 1);
    }
  }
}

const list = [...entries.values()].sort((a, b) => a.title.localeCompare(b.title));
const byLicence = new Map();
for (const e of list) byLicence.set(e.license ?? '(unrecorded)', (byLicence.get(e.license ?? '(unrecorded)') ?? 0) + 1);

/* ------------------------------------------------------------------------ output */

if (asJson) {
  console.log(JSON.stringify({ pack: manifest.id, images: list, audioEngines: [...engines], ownImages: ourImages }, null, 2));
  process.exit(0);
}

// CC BY-SA and GFDL are both copyleft; GFDL is the heavier of the two and arrives on
// Commons looking like any other free licence. Both classifications come from
// `lib/licence.mjs` so that this file and `pack-validate.mjs` cannot drift on what
// counts as share-alike or as GFDL either.
const shareAlike = list.filter((e) => licenceObligations(e.license).shareAlike);
const gfdl = list.filter((e) => licenceObligations(e.license).licenceText);
const publicDomain = list.filter((e) => licenceObligations(e.license).publicDomain);

const md = `# Attributions — ${manifest.name} (\`${manifest.id}\`)

**Generated by \`tools/pack-attributions.mjs\` from the pack itself. Do not edit by hand.**
Regenerate after any change to the pictures. The app builds its credits screen the same
way, from the live pack, so pictures added on the phone appear there too.

## Photographs

${list.length === 0 ? '_No third-party photographs in this pack yet._' : `${list.length} third-party photograph(s)${ourImages ? `, plus ${ourImages} taken by the family (no obligation)` : ''}.

| Picture | Author | Licence | Source | Used for |
|---|---|---|---|---|
${list.map((e) => `| ${e.title.replace(/\|/g, '/')} | ${e.creator ?? '**unrecorded**'} | ${e.licenseUrl ? `[${e.license}](${e.licenseUrl})` : (e.license ?? '**unrecorded**')} | ${e.sourceUrl ? `[link](${e.sourceUrl})` : '**unrecorded**'} | ${e.words.join(', ')} |`).join('\n')}

All photographs above were **cropped to square, resized to 512 px and re-encoded as JPEG**.
CC BY and CC BY-SA both require that modifications be indicated; this sentence is that
indication, and each entry records its own \`modified\` string in the pack.`}

## What these licences oblige

| Licence | Obligation |
|---|---|
| CC0 / Public domain | none |
| CC BY | name the author, name the licence, link to it, say that the image was changed |
| **CC BY-SA** | all of CC BY, **and the adapted image must itself be offered under the same licence** |
| **GFDL** | attribution, **the full licence text must ship with the work**, and 1.2-only cannot be relicensed as CC BY-SA |

${gfdl.length ? `**${gfdl.length} photograph(s) here are GFDL** (${gfdl.map((e) => e.words.join('/')).join(', ')}). That is the
heaviest obligation in this pack: the full GNU Free Documentation Licence text would have
to ship with the app, and a GFDL-1.2-only file cannot be relicensed as CC BY-SA. Harmless
while this stays a private family app. Before publishing, the cheap answer is to replace
those pictures — they are the mother's to retake anyway.

` : ''}${shareAlike.length ? `**${shareAlike.length} of the ${list.length} photographs here are share-alike.** Because the pipeline crops and
resizes, each of those cropped JPEGs is an adaptation and must itself be available under
CC BY-SA. That obligation attaches to **the image files, not to the app**: the photographs
are separate works collected alongside the code, not a derivative of it, so share-alike
does not reach \`src/\`. If the owner publishes, the honest discharge is this table in an
in-app credits screen plus a statement that the photographs are available under their
original terms.` : '_No share-alike photographs in this pack._'}

## Audio

${engines.size === 0 ? '_No audio in this pack yet._' : `| Engine | Clips |
|---|---|
${[...engines].sort((a, b) => b[1] - a[1]).map(([e, n]) => `| \`${e}\` | ${n} |`).join('\n')}`}

**The audio is the unsettled licensing question, not the photographs.** Every photograph
above has an explicit, public licence grant. The synthesised clips do not: \`edge-tts\`
drives Microsoft's Edge read-aloud endpoint and \`gTTS\` drives Google Translate's, and
neither publishes terms granting redistribution of the audio inside a product. For a
private family app this is a non-issue. Before publishing to a store it is the thing to
resolve, and the resolution is cheap because the pipeline already treats a recording and a
generated clip as interchangeable: re-record, re-import, and the question disappears.
See \`docs/design/open-questions-content.md\`.

## Emoji fallback

Fluent Emoji 3D (\`microsoft/fluentui-emoji\`) is **MIT**. The MIT notice ships once with
the app, not per image. It was chosen over OpenMoji specifically to avoid a second
share-alike obligation (\`spike-results.md\`).
`;

const outFile = packPaths(packDir).attribution;
if (check) {
  const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
  if (current !== md) {
    console.error(`${outFile} is out of date — run: node tools/pack-attributions.mjs ${packDir}`);
    process.exit(1);
  }
  console.log(`${outFile} is up to date (${list.length} photograph(s), ${byLicence.size} licence(s))`);
  process.exit(0);
}

writeFileSync(outFile, md);
console.log(`${outFile}: ${list.length} third-party photograph(s), ${ourImages} own, ${engines.size} audio engine(s)`);
for (const [lic, n] of [...byLicence].sort((a, b) => b[1] - a[1])) console.log(`  ${String(n).padStart(4)}  ${lic}`);
/*
 * CAN THIS PACK BE PUBLISHED? Asked through `lib/licence.mjs`, which is the same
 * predicate `pack-validate.mjs` asks, because this file and that one used to disagree.
 *
 * It refused to publish `packs/vi-seed` over `đèn` and `mũi` — both `"Public domain"`
 * with `creator: null` — by requiring an author from every image unconditionally. **A
 * public-domain work has no attribution obligation**: there is no rights-holder to
 * credit, and a null creator is the correct, honest representation of that rather than
 * missing data. It was a false blocker on the one screen where a false blocker is
 * expensive, because the way to clear it is to invent an author.
 *
 * What stays strict, and is the reason this is not simply relaxed: a CC BY, CC BY-SA or
 * GFDL image with no creator still fails hard, an unrecorded licence still fails hard,
 * and **a licence string nobody recognises is treated as requiring attribution** rather
 * than waved through.
 */
const unattributed = list.filter((e) => missingCredit(e).length > 0);
const needCredit = list.filter((e) => licenceObligations(e.license).attribution);
console.log(`  ${String(needCredit.length).padStart(4)}  require credit — all ${needCredit.length - unattributed.length} credited`);
if (publicDomain.length) {
  console.log(`  ${String(publicDomain.length).padStart(4)}  public domain / CC0 — no attribution obligation (${publicDomain.filter((e) => !e.creator).length} with no author, which is correct)`);
}
if (gfdl.length) {
  console.log(`  ${String(gfdl.length).padStart(4)}  GFDL — the full licence text must ship with the work`);
}
if (unattributed.length) {
  console.error(`\n${unattributed.length} photograph(s) cannot be attributed. This pack must not be published:`);
  for (const e of unattributed) {
    console.error(`  ${e.src} (${e.words.join(', ')}) — ${JSON.stringify(e.license ?? null)} is missing ${missingCredit(e).join(', ')}`);
  }
  process.exit(1);
}
